const AUTHENTICATORS = ["Meera Iyer", "Arjun Malhotra", "Sana Qureshi", "Vikram Desai", "Neha Bhatt"];

type Seed = {
  slug: string;
  name: string;
  brand: string;
  category: CategorySlug;
  subcategory: string;
  gender: Gender;
  price: number;
  retailPrice?: number;
  condition: Condition;
  conditionNotes: string;
  sizes?: SizeOption[];
  sizeSystem?: string;
  images: ProductImage[];
  description: string;
  colour: string;
  material: string;
  year?: string;
  includes: string[];
  details?: ProductDetail[];
  sellerId: string;
  status?: Product["status"];
  listedAt: string;
  views: number;
  saves: number;
  tags?: string[];
  pendingAuth?: boolean;
};

let counter = 0;

function p(seed: Seed): Product {
  counter += 1;
  const n = counter;
  const seller = sellerMap[seed.sellerId];
  const certNumber = String(20400 + n * 37).padStart(5, "0");
  const authDay = new Date(seed.listedAt);
  authDay.setDate(authDay.getDate() - 2);

  // Lead with the studio photograph when the piece has one; the original
  // photography follows as the editorial and detail views.
  const studio = STUDIO[seed.slug];
  const originals: ProductImage[] = seed.images.map((img) => ({ ...img, blur: img.blur ?? blurFor(img.src) }));
  const images: ProductImage[] = studio
    ? [{ src: `/catalog/${seed.slug}.webp`, alt: seed.images[0].alt, tone: "light", studio: true, blur: studio.blur }, ...originals]
    : originals;
  const offset = studio ? 1 : 0;

  return {
    id: `jb-${String(n).padStart(4, "0")}`,
    slug: seed.slug,
    name: seed.name,
    brand: seed.brand,
    category: seed.category,
    subcategory: seed.subcategory,
    gender: seed.gender,
    price: seed.price,
    retailPrice: seed.retailPrice,
    condition: seed.condition,
    conditionNotes: seed.conditionNotes,
    sizes: seed.sizes ?? [{ label: "One size", stock: 1 }],
    sizeSystem: seed.sizeSystem ?? "One size",
    images,
    cutout: studio && !studio.figure ? { src: `/cutouts/${seed.slug}.webp`, aspect: studio.cutAspect } : undefined,
    hotspots: studio ? HOTSPOTS[seed.slug] : undefined,
    angles: ANGLES[seed.slug]?.map((i) => i + offset),
    description: seed.description,
    colour: seed.colour,
    material: seed.material,
    year: seed.year,
    includes: seed.includes,
    details: seed.details ?? [],
    sellerId: seed.sellerId,
    authentication: seed.pendingAuth
      ? {
          status: "in-review",
          certificateId: `JB-${CODE[seed.category]}-${certNumber}`,
          checks: AUTH_CHECKS[seed.category],
        }
      : {
          status: "authenticated",
          certificateId: `JB-${CODE[seed.category]}-${certNumber}`,
          authenticatedOn: authDay.toISOString().slice(0, 10),
          authenticator: AUTHENTICATORS[n % AUTHENTICATORS.length],
          checks: AUTH_CHECKS[seed.category],
        },
    status: seed.status ?? "available",
    listedAt: seed.listedAt,
    views: seed.views,
    saves: seed.saves,
    tags: seed.tags ?? [],
    shipsFrom: seller?.location ?? "Mumbai",
  };
}

